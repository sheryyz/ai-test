"""Runs a knowledge-base health check against a registered agent and stores the report.

The knowledge base and the retriever both come from the agent (over the agent protocol when
it runs as its own process). Test questions are generated once by an LLM, checked and frozen
to benchmarks/<target>_kb_queries.jsonl, so retrieval scores are repeatable without a model.
Poisoned passages for the poisoning check are taken from the target's own suites: every
`poison_retrieval` injection, hand-written or generated by `consenttrace attacks`.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from consenttrace.adapters.base import KnowledgeAdapter
from consenttrace.adapters.http import HttpAgentAdapter
from consenttrace.core.loader import load_cases, load_contract
from consenttrace.core.registry import TargetSpec
from consenttrace.llm.client import ChatClient
from consenttrace.rag.kb_check import KBPassage, check_kb, poison_conflicts, score_planted, seed_faults
from consenttrace.schemas import InjectionMode


def knowledge_source(spec: TargetSpec, transport: str) -> KnowledgeAdapter:
    if transport == "http":
        if not spec.service_url:
            raise ValueError(f"{spec.name} 没有配置 service.url")
        return HttpAgentAdapter(spec.service_url, version=spec.versions[0])
    adapter = spec.adapter_class()(lambda: None)
    if not isinstance(adapter, KnowledgeAdapter):
        raise ValueError(f"{spec.name} 没有检索知识库")
    return adapter


def poisoned_passages(spec: TargetSpec) -> list[KBPassage]:
    contract = load_contract(spec.contract)
    seen: dict[str, KBPassage] = {}
    for path in dict.fromkeys(spec.suites.values()):
        for case in load_cases(path, contract):
            for inj in case.injections:
                payload = inj.payload
                if inj.mode is InjectionMode.POISON_RETRIEVAL and isinstance(payload, dict) and payload.get("text"):
                    seen.setdefault(
                        payload["text"], KBPassage(f"{case.case_id}", str(payload.get("title", "")), str(payload["text"]))
                    )
    return list(seen.values())


def read_queries(path: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    header: dict[str, Any] = {}
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("// "):
            header = json.loads(line[3:])
        elif line.strip():
            rows.append(json.loads(line))
    return header, rows


def run_kb_check(
    spec: TargetSpec,
    *,
    root: Path,
    runs_dir: Path,
    transport: str = "inprocess",
    client: ChatClient | None = None,
    regenerate_queries: bool = False,
    seed: int = 0,
) -> dict[str, Any]:
    source = knowledge_source(spec, transport)
    passages = [KBPassage(p["id"], p.get("title", ""), p.get("text", "")) for p in source.knowledge()]
    queries_path = root / "benchmarks" / f"{spec.name}_kb_queries.jsonl"
    generation = None
    if regenerate_queries or not queries_path.exists():
        if client is None:
            raise ValueError("没有冻结的检索测试题；生成需要模型（--llm）")
        from consenttrace.rag.llm import PROMPT_VERSION, generate_queries

        queries, generation = generate_queries(client, passages)
        header = {
            "target": spec.name,
            "model": client.model,
            "prompt_version": PROMPT_VERSION,
            "created_at": datetime.now(UTC).isoformat(timespec="seconds"),
        }
        queries_path.write_text(
            "\n".join(["// " + json.dumps(header, ensure_ascii=False)] + [json.dumps(q, ensure_ascii=False) for q in queries])
            + "\n",
            encoding="utf-8",
        )
    query_header, queries = read_queries(queries_path)

    report = check_kb(passages, queries=queries, search=source.search_knowledge)
    llm_review = None
    if client is not None:
        from consenttrace.rag.kb_check import neighbours
        from consenttrace.rag.llm import review_pairs

        by_id = {p.id: p for p in passages}
        candidates = {tuple(i["passages"]) for i in report["issues"] if i["kind"] == "conflict"}
        pairs = sorted(candidates | neighbours(passages))  # every pair a retriever would bring back together
        llm_review = {
            "model": client.model,
            "pairs": review_pairs(client, [(by_id[a], by_id[b]) for a, b in pairs]),
            "candidates": [list(c) for c in sorted(candidates)],
        }
        verdict = {tuple(r["pair"]): r for r in llm_review["pairs"]}
        for issue in report["issues"]:
            if issue["kind"] == "conflict":
                issue["llm"] = verdict.get(tuple(issue["passages"]))

    faulty, planted = seed_faults(passages, seed=seed)
    faulty_report = check_kb(faulty)
    seeded = score_planted(faulty_report, planted)
    clean = {(i["rule"], tuple(i["passages"])) for i in report["issues"]}
    planted_ids = {pid for f in planted for pid in f["passages"]}
    # new findings that touch no planted fault: the checker raising alarms the faults did not cause
    seeded["false_alarms"] = [
        i
        for i in faulty_report["issues"]
        if (i["rule"], tuple(i["passages"])) not in clean and not set(i["passages"]) & planted_ids
    ]

    poisons = poisoned_passages(spec)
    poisoning = poison_conflicts(passages, poisons)
    if client is not None:  # second opinion on each poisoned passage against the clauses retrieved with it
        from consenttrace.rag.kb_check import neighbours
        from consenttrace.rag.llm import review_pairs

        by_id = {p.id: p for p in passages}
        for row, poison in zip(poisoning, poisons, strict=True):
            near = sorted({x for pair in neighbours([*passages, poison]) if poison.id in pair for x in pair if x != poison.id})
            row["llm"] = review_pairs(client, [(by_id[n], poison) for n in near])
            row["llm_flagged"] = any(r["conflict"] for r in row["llm"])
    result = {
        "target": spec.name,
        "transport": transport,
        "checked_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "knowledge": [p.__dict__ for p in passages],
        **report,
        "queries_source": {**query_header, "path": str(queries_path.relative_to(root)), "count": len(queries)},
        "query_generation": generation,
        "llm_review": llm_review,
        "seeded": seeded,
        "poisoning": {
            "passages": len(poisoning),
            "flagged": sum(p["flagged"] for p in poisoning),
            "llm_flagged": sum(bool(p.get("llm_flagged")) for p in poisoning) if client is not None else None,
            "rows": poisoning,
        },
    }
    out = runs_dir / "kb_checks" / f"{spec.name}-{datetime.now(UTC):%Y%m%d-%H%M%S}"
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.json").write_text(json.dumps(result, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
    result["path"] = str(out)
    return result


def latest_kb_report(runs_dir: Path, target: str) -> dict[str, Any] | None:
    folder = runs_dir / "kb_checks"
    found = sorted(folder.glob(f"{target}-*/report.json")) if folder.exists() else []
    return json.loads(found[-1].read_text(encoding="utf-8")) if found else None
